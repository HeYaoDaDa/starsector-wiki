#!/usr/bin/env python3
"""Polish the auto-drafted Askonia quest packages (sd7s + sdse).

Zero-handwriting policy: names come from official_names.py (verified
quotes of jar strings), stage briefings are extracted official text
(hand-PAIRED, never hand-written), character titles only where they can
be traced to official CN text. No summaries, no flags glossary, no
hand-written prose — those live in the frontend editorial layer
(src/questEditorial.ts, generated by gen_editorial.py).
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
QUESTS = os.path.join(HERE, 'quests')

from official_names import OFFICIAL_NAMES, OFFICIAL_TITLES, PERSON_NAMES  # noqa: E402


def load(name):
    with open(os.path.join(QUESTS, name), encoding='utf-8') as f:
        return json.load(f)


def save(name, data):
    with open(os.path.join(QUESTS, name), 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)


def bi(en, zh):
    return {'en': en, 'zh': zh or en}


def apply_official_characters(pkg_id, characters, mission):
    """人物：官方名 + 仅限可溯源头衔；其余只留名字。"""
    out = []
    for c in characters:
        cid = c['id']
        name = PERSON_NAMES.get(cid)
        title = OFFICIAL_TITLES.get((pkg_id, cid))
        entry = {
            'id': cid,
            'name': bi(*name) if name else bi(cid, cid),
            'title': bi(*title) if title else None,
        }
        if entry['title'] is None:
            del entry['title']
        out.append(entry)
    return out


