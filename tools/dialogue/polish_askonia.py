def build_stages(briefings, flags):
    out = []
    for stage_id, en, zh in briefings:
        out.append({
            'id': stage_id,
            'flag': flags.get(stage_id, f'${stage_id.lower()}'),
            'briefing': bi(en, zh),
        })
    return out


IGNORE_PATTERNS_BASE = [
    '^DEV', '^dev[A-Z]', 'test', 'Test', 'TEST',
    '^relLevel', '^flavorText', '^bar_desc',
]

# 七子：跨弧线降噪
SD7S_IGNORE = IGNORE_PATTERNS_BASE + [
    '^sdse', '^SDSE', '^PostSDSE', '^postSDSE',
    '^sdsw', '^SDSW', '^PostSDSW', '^postSDSW',
    '^sdr[A-Z]', '^SDR[A-Z]', '^PostSDR', '^postSDR',
]
SDSE_IGNORE = IGNORE_PATTERNS_BASE + [
    '^sdtu', '^SDTU', '^PostSDTU', '^postSDTU', '^postSDT',
    '^sd7s', '^SD7S', '^PostSD7S', '^postSD7S',
    '^sdsw', '^SDSW', '^PostSDSW', '^postSDSW',
    '^sdr[A-Z]', '^SDR[A-Z]',
]
COMMON_IGNORE_RULES = [
    'relLevelDiktatSDTU', 'relLevelDiktatSD7S', 'HyderGreetDefaultSD',
    'sdBarRaid0', 'ZGRacknowledgeDiktatB',
]


def main() -> None:
    # ---- the_seven_sons ----
    sd7s = load('the_seven_sons.json')
    mission = 'sd7s'
    name = OFFICIAL_NAMES.get(mission)
    if name:
        sd7s['name'] = bi(*name)
    else:
        sd7s.pop('name', None)  # 前端 wiki 标签兜底
    sd7s.pop('summary', None)
    sd7s.pop('flags', None)
    sd7s['factionId'] = 'sindrian_diktat'
    sd7s['stages'] = build_stages(SD7S_STAGE_BRIEFINGS, SD7S_STAGE_FLAGS)
    sd7s['characters'] = apply_official_characters(
        'the_seven_sons', sd7s.get('characters', []), mission)
    sd7s['ignoreRulePatterns'] = SD7S_IGNORE
    sd7s['ignoreRules'] = COMMON_IGNORE_RULES
    # 场景标题/地点是公式化文本，交由前端渲染；数据里删除
    for sc in sd7s.get('scenes', []):
        sc.pop('title', None)
        sc.pop('location', None)
    save('the_seven_sons.json', sd7s)

    # ---- the_supreme_executor ----
    sdse = load('the_supreme_executor.json')
    mission = 'sdse'
    name = OFFICIAL_NAMES.get(mission)
    if name:
        sdse['name'] = bi(*name)
    else:
        sdse.pop('name', None)
    sdse.pop('summary', None)
    sdse.pop('flags', None)
    sdse['factionId'] = 'sindrian_diktat'
    sdse['stages'] = build_stages(SDSE_STAGE_BRIEFINGS, SDSE_STAGE_FLAGS)
    sdse['characters'] = apply_official_characters(
        'the_supreme_executor', sdse.get('characters', []), mission)
    sdse['ignoreRulePatterns'] = SDSE_IGNORE
    sdse['ignoreRules'] = COMMON_IGNORE_RULES
    for sc in sdse.get('scenes', []):
        sc.pop('title', None)
        sc.pop('location', None)
    save('the_supreme_executor.json', sdse)

    print('polished: the_seven_sons.json, the_supreme_executor.json (zero-handwriting)')


if __name__ == '__main__':
    main()
